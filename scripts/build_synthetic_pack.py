def doc(path,title,sections):
    path.parent.mkdir(parents=True,exist_ok=True)
    d=Document(); d.add_heading(title,0)
    d.add_paragraph('課程模擬文件｜虛構學校與資料｜非真實校務紀錄')
    for h,b in sections:
        d.add_heading(h,1)
        if isinstance(b,list):
            for item in b: d.add_paragraph(item,style='List Bullet')
        else: d.add_paragraph(b)
    d.save(path)

def csvfile(path,headers,rows):
    path.parent.mkdir(parents=True,exist_ok=True)
    with path.open('w',encoding='utf-8-sig',newline='') as f:
        w=csv.writer(f,lineterminator='\n'); w.writerow(headers); w.writerows(rows)

def xlsx(path,headers,rows,sheet='資料'):
    path.parent.mkdir(parents=True,exist_ok=True)
    wb=Workbook(); ws=wb.active; ws.title=sheet
    ws.append(headers)
    for row in rows: ws.append(row)
    ws.freeze_panes='A2'; ws.auto_filter.ref=ws.dimensions
    for c in ws[1]:
        c.font=Font(bold=True,color='FFFFFF')
        c.fill=PatternFill('solid',fgColor='245B70')
    for col in ws.columns:
        ws.column_dimensions[col[0].column_letter].width=min(max(max(len(str(c.value or '')) for c in col)+2,12),36)
    wb.save(path)

def pdf(path,title,lines):
    path.parent.mkdir(parents=True,exist_ok=True)
    if 'STSong-Light' not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(UnicodeCIDFont('STSong-Light'))
    c=canvas.Canvas(str(path),pagesize=A4); _,h=A4; y=h-48
    c.setFont('STSong-Light',15); c.drawString(42,y,title); y-=24
    c.setFont('STSong-Light',9); c.drawString(42,y,'課程模擬文件｜SYNTHETIC TRAINING DATA'); y-=28
    c.setFont('STSong-Light',10)
    for line in lines:
        if y<50: c.showPage(); y=h-48; c.setFont('STSong-Light',10)
        c.drawString(42,y,line[:70]); y-=18
    c.save()

